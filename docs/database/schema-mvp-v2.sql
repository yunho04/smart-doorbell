-- =========================================================
-- AIoT Smart Doorbell - MVP v2 Database Schema
-- PostgreSQL 16
-- =========================================================


-- =========================================================
-- 0. 기존 개발용 테이블 삭제
-- 새 개발 DB를 초기화할 때만 사용한다. 기존 개발 DB에는 실행하지 않는다.
-- =========================================================
DROP TABLE IF EXISTS feedbacks CASCADE;
DROP TABLE IF EXISTS event_responses CASCADE;
DROP TABLE IF EXISTS media_files CASCADE;
DROP TABLE IF EXISTS events CASCADE;
DROP TABLE IF EXISTS devices CASCADE;


-- =========================================================
-- 1. DEVICES
-- Raspberry Pi 스마트 도어벨 장치
-- =========================================================

CREATE TABLE devices (
    device_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    device_name VARCHAR(100) NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'OFFLINE',

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_device_status
        CHECK (status IN ('ONLINE', 'OFFLINE'))
);


-- =========================================================
-- 2. EVENTS
-- 한 번의 방문 상황 전체를 관리하는 핵심 테이블
-- =========================================================

CREATE TABLE events (
    event_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    device_id BIGINT NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'DETECTED',

    started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    
    last_detected_at TIMESTAMP,

    ended_at TIMESTAMP,

    risk_level VARCHAR(20),

    summary TEXT,

    response_code VARCHAR(50),

    response_text TEXT,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_events_device
        FOREIGN KEY (device_id)
        REFERENCES devices(device_id),

    CONSTRAINT chk_event_status
        CHECK (
            status IN (
                'DETECTED',
                'ANALYZING',
                'RESPONDING',
                'COMPLETED',
                'FAILED'
            )
        ),

    CONSTRAINT chk_risk_level
        CHECK (
            risk_level IS NULL
            OR risk_level IN ('LOW', 'MEDIUM', 'HIGH')
        )
);


-- =========================================================
-- 3. MEDIA_FILES
-- Event와 관련된 사진/음성/영상 파일 경로 저장
-- 실제 파일 자체는 DB에 저장하지 않음
-- 대표사진은 IMAGE로 저장하고 /uploads/representative-images/ 경로로 구분
-- =========================================================

CREATE TABLE media_files (
    media_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    event_id BIGINT NOT NULL,

    media_type VARCHAR(20) NOT NULL,

    file_path VARCHAR(500) NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_media_event
        FOREIGN KEY (event_id)
        REFERENCES events(event_id)
        ON DELETE CASCADE,

    CONSTRAINT chk_media_type
        CHECK (
            media_type IN ('IMAGE', 'AUDIO', 'VIDEO')
        )
);

-- =========================================================
-- 4. EVENT_RESPONSES
-- Event 진행 중 LLM이 선택한 응답 기록
-- 한 Event에 여러 응답이 존재할 수 있음
-- =========================================================

CREATE TABLE event_responses (
    response_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    event_id BIGINT NOT NULL,

    response_code VARCHAR(50) NOT NULL,

    response_text TEXT NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_event_responses_event
        FOREIGN KEY (event_id)
        REFERENCES events(event_id)
        ON DELETE CASCADE
);

-- =========================================================
-- 5. FEEDBACKS
-- Event당 AI 위험도 판단 정확도에 대한 사용자 평가 1건
-- =========================================================

CREATE TABLE feedbacks (
    feedback_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    event_id BIGINT NOT NULL UNIQUE,

    accuracy_level VARCHAR(20) NOT NULL,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_feedback_event
        FOREIGN KEY (event_id)
        REFERENCES events(event_id)
        ON DELETE CASCADE,

    CONSTRAINT chk_feedback_accuracy
        CHECK (
            accuracy_level IN ('HIGH', 'MEDIUM', 'LOW')
        )
);
-- =========================================================
-- 6. 조회 성능을 위한 인덱스
-- =========================================================

CREATE INDEX idx_events_device_id
    ON events(device_id);

CREATE INDEX idx_events_started_at
    ON events(started_at);

CREATE INDEX idx_media_files_event_id
    ON media_files(event_id);

CREATE INDEX idx_event_responses_event_id
    ON event_responses(event_id);

CREATE INDEX idx_feedbacks_event_id
    ON feedbacks(event_id);

